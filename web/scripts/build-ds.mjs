// Wraps the OtterMeet design-system bundle (a classic script that reads window.React and writes
// window.OtterMeet) in an ES module function, so it can run during server rendering as well as in the browser.
// vendor/bundle.js stays byte-for-byte the artifact's copy. Runs before `dev` and `build`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../src/ds/', import.meta.url));
const source = readFileSync(dir + 'vendor/bundle.js', 'utf8');

const out = `// Generated by scripts/build-ds.mjs from src/ds/vendor/bundle.js. Do not edit.
export default function loadOtterMeet(window) {
${source}
return window.OtterMeet;
}
`;

writeFileSync(dir + 'bundle.generated.js', out);
